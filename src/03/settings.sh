#!/usr/bin/env bash
# settings.sh — файл глобальных настроек проекта.
# Содержит:
# • ограничения длины имён файлов и директорий;
# • путь к лог-файлу;
# • системные директории, исключённые из поиска;
# • ANSI-коды цветов для оформления вывода;
# • рабочие константы скрипта.

# Количество аргументов запуска main.sh
LEN_ARGS=1

# Путь к лог-файлу Part 2.
# Используется для режима очистки по лог-файлу.

LOG_DIR="$SCRIPT_DIR/../02/logs"
LOG_PATTERN="$LOG_DIR"/log_*.tsv

# LOG_FILE="$LOG_DIR/log_*.tsv"

# Ограничения длины имени директории
MIN_LEN_DIR=5
MAX_LEN_DIR=7

# Ограничения длины имени файла без расширения
MIN_LEN_FILE=5
MAX_LEN_FILE=7

# Ограничения длины расширения файла
MIN_LEN_EXT=1
MAX_LEN_EXT=3

# Текущая дата в формате DDMMYY.
# Используется при формировании масок имён.
TDATE=$(date +"%d%m%y")

# ANSI-коды цветов для оформления сообщений
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
MAGENTA='\033[0;35m'
WHITE='\033[1;37m'
GRAY='\033[0;90m'

# Жирный текст
BOLD='\033[1m'

# Сброс ANSI-оформления
NC='\033[0m'

# Список системных директорий,
# исключённых из поиска и удаления.
EXCLUDE=(
    "*/bin*"
    "*/sbin*"
    "/proc*"
    "/sys*"
    "/dev*"
    "/run*"
)

# Базовая директория для тестирования скрипта
FIRST_DIR="/"
