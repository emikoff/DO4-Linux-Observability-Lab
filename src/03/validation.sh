#!/usr/bin/env bash
# validation.sh — модуль проверки входных и интерактивных параметров.
#
# Содержит функции валидации:
# • количества аргументов запуска;
# • режима очистки;
# • буквенных наборов;
# • шаблона имени файла name.ext;
# • размера файла;
# • даты в формате DDMMYY;
# • даты в формате DD.MM.YYYY;
# • времени в формате HH:MM.
#
# Файл не запускается самостоятельно.
# Подключается из main.sh после settings.sh,
# так как использует глобальные настройки и ANSI-коды цветов.

# ==================================================
# 0. Вспомогательные функции
# ==================================================

# Печатает справку по запуску main.sh.
# Использует глобальную переменную LEN_ARGS из settings.sh.
show_help() {
    echo
    echo -e "${CYAN}${BOLD}======================================================${NC}"
    echo -e "${WHITE}${BOLD}Справка по запуску${NC}"
    echo -e "${CYAN}${BOLD}======================================================${NC}"
    echo -e "  ${GRAY}•${NC} Ожидается аргументов: ${YELLOW}$LEN_ARGS${NC}"
    echo
    echo -e "${BLUE}${BOLD}Способ очистки:${NC}"
    echo -e "  ${GREEN}1${NC} — по лог-файлу"
    echo -e "  ${GREEN}2${NC} — по дате и времени создания"
    echo -e "  ${GREEN}3${NC} — по маске имени"
    echo
    echo -e "${BLUE}${BOLD}Примеры запуска:${NC}"
    echo -e "  ${WHITE}./main.sh 1${NC}"
    echo -e "  ${WHITE}./main.sh 2${NC}"
    echo -e "  ${WHITE}./main.sh 3${NC}"
    echo
    echo -e "${BLUE}${BOLD}Пояснение:${NC}"
    echo -e "  ${GRAY}После выбора режима дополнительные данные${NC}"
    echo -e "  ${GRAY}запрашиваются во время выполнения скрипта.${NC}"
    echo -e "${CYAN}${BOLD}======================================================${NC}"
    echo
}

# ==================================================
# 1. Общая проверка аргументов
# ==================================================

# Проверяет количество аргументов запуска скрипта.
# Аргументы:
#   все аргументы, переданные в main.sh.
# При ошибке:
#   печатает сообщение, показывает справку и завершает скрипт с кодом 1.
validate_args_count() {
    if [ $# -ne "$LEN_ARGS" ]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} ожидается $LEN_ARGS аргументов, получено $#"
        show_help
        exit 1
    fi
}

# Проверяет режим очистки.
# Аргументы:
#   $1 — выбранный режим очистки.
# Допустимые значения:
#   1 — по лог-файлу;
#   2 — по дате и времени;
#   3 — по маске имени.
# При ошибке:
#   печатает сообщение, показывает справку и завершает скрипт с кодом 1.
validate_cleanup_mode_value() {
    local el="$1"

    if ! [[ "$el" =~ ^[1-3]+$ ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} параметр должен содержать только цифры от 1 до 3"
        show_help
        exit 1
    fi
}

# Проверяет дату из маски имени.
# Аргументы:
#   $1 — дата из имени файла или директории.
# Ожидаемый формат:
#   DDMMYY, ровно 6 цифр.
# Возвращает:
#   0 — дата прошла проверку;
#   1 — формат неверный.
validate_date_mask() {
    local el="$1"

    if ! [[ "$el" =~ ^[0-9]+$ ]] || [[ "${#el}" != 6 ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} дата должна быть в формате ${WHITE}DDMMYY${NC} и содержать 6 цифр ${GRAY}(пример: ${WHITE}080526${GRAY})${NC}"
        return 1
    fi
}


# ==================================================
# 4. Проверка буквенных параметров
# ==================================================

# Проверяет, что строка содержит только английские буквы.
# Аргументы:
#   $1 — проверяемая строка.
# Возвращает:
#   0 — строка состоит только из английских букв;
#   1 — найдены другие символы.
# Примечание:
#   длина строки проверяется отдельно в validate_length_range.
validate_letters() {
    local el="$1"

    if ! [[ "$el" =~ ^[a-zA-Z]+$ ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} параметр должен содержать только английские буквы"
        return 1
    fi
}

# Проверяет длину строки.
# Аргументы:
#   $1 — проверяемая строка;
#   $2 — минимальная длина, по умолчанию 1;
#   $3 — максимальная длина, по умолчанию 7.
# Возвращает:
#   0 — длина попадает в диапазон;
#   1 — строка слишком короткая или слишком длинная.
validate_length_range() {
    local el="$1"
    local min_len="${2:-1}"
    local max_len="${3:-7}"


    if [ "${#el}" -lt "$min_len" ] || [ "${#el}" -gt "$max_len" ]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} длина ${WHITE}'$el'${NC} равна ${YELLOW}${#el}${NC}, ожидается от ${GREEN}$min_len${NC} до ${GREEN}$max_len${NC} символов"
        return 1
    fi
}

# ==================================================
# 5. Проверка параметра file.ext
# ==================================================

# Проверяет базовый формат file.ext:
# - до точки есть хотя бы один символ;
# - после точки есть хотя бы один символ.
# Аргументы:
#   $1 — строка с шаблоном имени файла.
# Возвращает:
#   0 — базовый формат корректен;
#   1 — нет имени, точки или расширения.
# Примечание:
#   количество точек проверяется отдельно в validate_one_dot.
validate_file_pattern() {
    local str="$1"

    if [[ ! "$str" =~ ^.+\..+$ ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} неверный формат ${GRAY}(нужно ${WHITE}'имя.расширение'${GRAY})${NC}"
        return 1
    fi
}

# Проверяет, что в строке ровно одна точка.
# Аргументы:
#   $1 — строка с шаблоном имени файла.
# Возвращает:
#   0 — точка ровно одна;
#   1 — точек нет или их больше одной.
validate_one_dot() {
    local str="$1"

    # После удаления всех символов, кроме точек, длина строки равна их количеству.
    local dots_only="${str//[^.]/}"

    if [[ ${#dots_only} -ne 1 ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} должна быть ровно одна точка ${GRAY}(сейчас: ${YELLOW}${#dots_only}${GRAY})${NC}"
        return 1
    fi
}


# ==================================================
# 6. Проверка размера файла
# ==================================================

# Проверяет формат размера файла.
# Аргументы:
#   $1 — размер файла, введённый пользователем.
# Ожидаемый формат:
#   NMb, например 10Mb. Регистр суффикса не важен.
# Возвращает:
#   0 — формат корректен;
#   1 — формат неверный.
validate_size_format() {
    local size_arg="${1,,}"

    if ! [[ "$size_arg" =~ ^[0-9]+(mb)$ ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} некорректный формат размера ${WHITE}'$1'${NC}"
        return 1
    fi
}

# Проверяет допустимый диапазон размера файла.
# Аргументы:
#   $1 — размер файла в мегабайтах без суффикса.
# Возвращает:
#   0 — размер больше 0 и не превышает 100;
#   1 — размер вне допустимого диапазона.
validate_size_value() {
    local size_val=$((10#$1))

    if (( size_val <= 0 )) || (( size_val > 100 )); then
        echo -e "${RED}${BOLD}Ошибка:${NC} некорректный размер ${WHITE}'$1'${NC}"
        return 1
    fi
}

# ==================================================
# 7. Проверка режима очистки, даты и времени
# ==================================================

# Проверяет параметр запуска main.sh.
# Аргументы:
#   все аргументы, переданные в main.sh.
# Ожидается:
#   один аргумент — режим очистки: 1, 2 или 3.
# При ошибке:
#   завершает скрипт через validate_args_count
#   или validate_cleanup_mode_value.
validate_cleanup_mode() {
    validate_args_count "$@"
    validate_cleanup_mode_value "$1"
}

# Проверяет дату, введённую пользователем.
# Аргументы:
#   $1 — дата в формате DD.MM.YYYY.
# Возвращает:
#   0 — формат и основные диапазоны корректны;
#   1 — дата введена неверно.
# Проверяются:
#   формат, день 1-31, месяц 1-12, год не больше текущего.
validate_date_human() {
    local date="$1"
    local day month year
    
    if ! [[ "$date" =~ ^[0-9]{2}\.[0-9]{2}\.[0-9]{4}$ ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} дата должна быть в формате ${WHITE}DD.MM.YYYY${NC}"
        return 1
    fi
    
    # 10# защищает от интерпретации чисел с ведущим нулём как восьмеричных.
    day=$((10#${date:0:2}))
    month=$((10#${date:3:2}))
    year=$((10#${date:6:4}))

    if (( day < 1 || day > 31 )); then
        echo -e "${RED}${BOLD}Ошибка:${NC} день должен быть от ${GREEN}1${NC} до ${GREEN}31${NC}"
        return 1
    fi

    if (( month < 1 || month > 12 )); then
        echo -e "${RED}${BOLD}Ошибка:${NC} месяц должен быть от ${GREEN}1${NC} до ${GREEN}12${NC}"
        return 1
    fi

    if (( year < 0 || year > $(date +"%Y") )); then
        echo -e "${RED}${BOLD}Ошибка:${NC} год должен быть не больше текущего"
        return 1
    fi
}

# Проверяет время, введённое пользователем.
# Аргументы:
#   $1 — время в формате HH:MM.
# Возвращает:
#   0 — формат и диапазоны корректны;
#   1 — время введено неверно.
# Проверяются:
#   часы 00-23 и минуты 00-59.
validate_time_human() {
    local time="$1"
    local hour minute

    if ! [[ "$time" =~ ^[0-9]{2}\:[0-9]{2}$ ]]; then
        echo -e "${RED}${BOLD}Ошибка:${NC} время должно быть в формате ${WHITE}HH:MM${NC}"
        return 1
    fi

    # 10# защищает значения 08 и 09 от ошибки восьмеричного числа.
    hour=$((10#${time:0:2}))
    minute=$((10#${time:3:2}))

    if (( hour < 0 || hour > 23 )); then
        echo -e "${RED}${BOLD}Ошибка:${NC} час должен быть от ${GREEN}00${NC} до ${GREEN}23${NC}"
        return 1
    fi

    if (( minute < 0 || minute > 59 )); then
        echo -e "${RED}${BOLD}Ошибка:${NC} минуты должны быть от ${GREEN}00${NC} до ${GREEN}59${NC}"
        return 1
    fi
}

# Проверка, что аргумент — целое число

validate_positive_integer() {
    local el="$1"
    local max_num="$2"

    if ! [[ "$el" =~ ^[0-9]+$ ]]; then
        echo -e "${RED}Ошибка: '$el' не является целым числом${NC}"
        show_help
        exit 1
    fi
    if (( "$el" < 1 || "$el" > "$max_num" )); then
        echo -e "${RED}Значение '$el' должно быть в пределах от 1 до $max_num ${NC}"
        show_help
        exit 1
    fi
}